static uint8_t unary_xor8 (uint8_t x) {
    x ^= x >> 4;
    x ^= x >> 2;
    x ^= x >> 1;
    return x & 0x01;
}

static uint8_t unary_xor16 (uint16_t x) {
    x ^= x >> 8;
    x ^= x >> 4;
    x ^= x >> 2;
    x ^= x >> 1;
    return x & 0x01;
}

uint8_t small_block_len_encode (uint8_t msg) {
    uint8_t parity = 0;

    for (uint8_t i = 0; i < 8; i++) {
        parity |= (unary_xor8(msg & gen_matrix [i])) << (7-i);
    }

    return parity;
}

uint8_t small_block_len_decode (uint16_t encoded) {
    uint8_t syndrome = 0;

    for (uint8_t i = 0; i < 8; i++) {
        syndrome  |= (unary_xor16(encoded & parity_check [i])) << (7-i);
    }

    return (encoded >> 8) ^ coset [syndrome];
}